"""Regression coverage for the predictor actually carried by v3/v4 payloads."""

import numpy as np
import pytest

from timeflowcodec.decoder import decode_tfc_to_video
from timeflowcodec.encoder import encode_video_to_tfc
from timeflowcodec.format import parse_plane_payload_v3, parse_plane_payload_v4


@pytest.mark.parametrize("version", [3, 4])
@pytest.mark.parametrize("samples", [[0, 0, 0, 255, 255], [255, 255, 255, 0, 0]])
@pytest.mark.parametrize("compression", [0, 3])
def test_raw_predictor_clipping_does_not_shift_pixels(monkeypatch, tmp_path, version, samples, compression):
    frames = np.broadcast_to(np.array(samples, dtype=np.uint8)[:, None, None, None], (5, 2, 2, 3)).copy()
    monkeypatch.setattr("timeflowcodec.encoder.imageio.get_reader", lambda _: iter(frames))
    output = tmp_path / "step.tfc"
    encode_video_to_tfc(
        "synthetic", str(output), container_version=version, preset="custom",
        tiling=1, tau=0, payload_comp_type=compression,
    )
    decoded = decode_tfc_to_video(str(output), None)
    assert np.max(np.abs(decoded.astype(int) - frames.astype(int))) <= 1


@pytest.mark.parametrize("version", [3, 4])
def test_long_raw_sequence_preserves_slope_quantization_error(monkeypatch, tmp_path, version):
    t = np.arange(1001)
    frames = np.empty((1001, 1, 2, 3), dtype=np.uint8)
    frames[:, 0, 0, :] = np.clip(np.rint(0.21 * t + 10 * np.sin(t)), 0, 255)[:, None]
    frames[:, 0, 1, :] = np.clip(np.rint(255 - 0.23 * t + 9 * np.cos(t)), 0, 255)[:, None]
    monkeypatch.setattr("timeflowcodec.encoder.imageio.get_reader", lambda _: iter(frames))
    output = tmp_path / "ramp.tfc"
    encode_video_to_tfc("synthetic", str(output), container_version=version, tiling=1, tau=0,
                        payload_comp_type=0)
    decoded = decode_tfc_to_video(str(output), None)
    assert np.max(np.abs(decoded.astype(int) - frames.astype(int))) <= 1


@pytest.mark.parametrize("version", [3, 4])
def test_linear_tile_sets_shared_raw_predictor_scale(monkeypatch, tmp_path, version):
    import struct

    from timeflowcodec import encoder

    frames = np.empty((5, 1, 2, 3), dtype=np.uint8)
    frames[:, 0, 0, :] = np.array([0, 63, 126, 189, 252])[:, None]
    frames[:, 0, 1, :] = np.array([0, 0, 0, 105, 105])[:, None]
    monkeypatch.setattr("timeflowcodec.encoder.imageio.get_reader", lambda _: iter(frames))
    name = f"build_plane_payload_v{version}"
    original = getattr(encoder, name)
    checked = []

    def check_residuals(segments, compression):
        # Independent scalar oracle: linear slope 63 sets the float32 wire scale;
        # the step sequence has fitted a=-21 and b=31.5. Its stored intercept is 0.
        scale = struct.unpack("<f", struct.pack("<f", 63 / 32767))[0]
        slope = round(31.5 / scale) * scale
        expected = [round(float(value) - slope * t) for t, value in enumerate([0, 0, 0, 105, 105])]
        np.testing.assert_array_equal(segments[0]["raw_residuals"], [expected])
        checked.append(True)
        return original(segments, compression)

    monkeypatch.setattr(encoder, name, check_residuals)
    output = tmp_path / "mixed.tfc"
    encode_video_to_tfc("synthetic", str(output), container_version=version, tiling=1, tau=0,
                        payload_comp_type=0)
    assert len(checked) == 3
    decoded = decode_tfc_to_video(str(output), None)
    assert np.max(np.abs(decoded.astype(int) - frames.astype(int))) <= 1


@pytest.mark.parametrize("parser,hex_payload", [
    (parse_plane_payload_v3,
     "01000000040000000300000003000000000180388001c0380100000001000000010000000100065a1eff7f7801a0555556d5ff7f0000"),
    (parse_plane_payload_v4,
     "01000000040000000300000003000000000180388001c038010000000100000001000000000000000100065a1eff7f7801a0555556d5ff7f0000"),
])
def test_pre_fix_payloads_remain_readable(parser, hex_payload):
    # Captured from the old writers before this fix, not generated by the new implementation.
    segment = parser(bytes.fromhex(hex_payload), 0)[0]
    assert segment["length"] == 4
    assert segment["tfc_params"][1]["a"] == 90
    assert segment["raw_predictors"][0]["a"] == 120
    np.testing.assert_allclose(segment["raw_residuals"], [[2, -1, 3, 0]], atol=0.001)
